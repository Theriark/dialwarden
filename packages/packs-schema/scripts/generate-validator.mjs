// Writes src/generated/validate-pack.ts, the pack.json validator, from
// src/pack.schema.json with Ajv's standalone code generation. The module it
// writes is plain code with no Ajv, no eval and no new Function, so the same
// validator runs in the server and in the browser under the app's CSP.
//
// The file is generated, never committed: the package's build and typecheck
// scripts run this script first, and the root vitest config runs setup()
// below before the tests.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

/* eslint-disable security/detect-non-literal-fs-filename -- the package's own files */

const SCHEMA_FILE = new URL("../src/pack.schema.json", import.meta.url);
const OUTPUT_DIR = new URL("../src/generated/", import.meta.url);
const OUTPUT_FILE = new URL("validate-pack.ts", OUTPUT_DIR);

const HEADER = [
  "/* eslint-disable */",
  "// @ts-nocheck",
  "// Generated by packages/packs-schema/scripts/generate-validator.mjs from",
  "// src/pack.schema.json. Do not edit and do not commit.",
  "",
].join("\n");

/** The validator module source for the schema file. */
export function generateValidatorSource() {
  const schema = JSON.parse(readFileSync(SCHEMA_FILE, "utf8"));
  const ajv = new Ajv2020({
    strict: true,
    strictTypes: false,
    allErrors: true,
    discriminator: true,
    // String lengths count UTF-16 code units, so the generated code needs no
    // Ajv runtime helper (ucs2length).
    unicode: false,
    code: { source: true, esm: true, lines: true },
  });
  const validate = ajv.compile(schema);
  const code = standaloneCode(ajv, validate);
  if (/\brequire\(/.test(code)) {
    throw new Error("the generated validator needs an Ajv runtime helper");
  }
  return `${HEADER}${code}\n`;
}

/** Writes the module when it is missing or out of date. */
export function writeValidator() {
  const source = generateValidatorSource();
  if (existsSync(OUTPUT_FILE) && readFileSync(OUTPUT_FILE, "utf8") === source) {
    return;
  }
  mkdirSync(OUTPUT_DIR, { recursive: true });
  writeFileSync(OUTPUT_FILE, source);
}

/** vitest globalSetup: the tests import the generated module. */
export function setup() {
  writeValidator();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeValidator();
}
